// Builds supabase/fresh-install.sql: the full database structure for a new,
// empty Supabase project, from supabase/schema.sql.
//
// schema.sql is the history of every change, run in order on the original
// project — so replaying it on an empty project reproduces the same tables,
// columns, functions, triggers and policies. What it can't replay as-is are
// the statements that insert content (tips, challenges): on an empty project
// they fail (challenges point at stages that don't exist yet) or would
// duplicate the content that scripts/copy-reference-data.mjs copies over
// from the old project. Those inserts are replaced by a comment; everything
// else is kept verbatim. Updates and deletes stay — on empty tables they
// simply touch no rows.
//
// Usage: node scripts/build-fresh-install.mjs

import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = "supabase/schema.sql";
const TARGET = "supabase/fresh-install.sql";
const CONTENT_TABLES = ["parent_tip_rules", "challenges", "child_challenges"];

// Splits SQL into statements at top-level semicolons, skipping those inside
// '...' strings, $tag$...$tag$ bodies and -- comments.
function splitStatements(sql) {
  const statements = [];
  let start = 0;
  let i = 0;
  while (i < sql.length) {
    const ch = sql[i];
    if (ch === "-" && sql[i + 1] === "-") {
      const end = sql.indexOf("\n", i);
      i = end === -1 ? sql.length : end + 1;
    } else if (ch === "'") {
      i++;
      while (i < sql.length) {
        if (sql[i] === "'" && sql[i + 1] === "'") i += 2;
        else if (sql[i] === "'") { i++; break; }
        else i++;
      }
    } else if (ch === "$") {
      const tag = /^\$[A-Za-z_]*\$/.exec(sql.slice(i));
      if (tag) {
        const close = sql.indexOf(tag[0], i + tag[0].length);
        i = close === -1 ? sql.length : close + tag[0].length;
      } else {
        i++;
      }
    } else if (ch === ";") {
      statements.push(sql.slice(start, i + 1));
      start = i + 1;
      i++;
    } else {
      i++;
    }
  }
  statements.push(sql.slice(start));
  return statements;
}

// Where the statement's code begins, after any leading blank lines/comments.
function codeStart(statement) {
  let i = 0;
  while (i < statement.length) {
    if (/\s/.test(statement[i])) i++;
    else if (statement.startsWith("--", i)) {
      const end = statement.indexOf("\n", i);
      i = end === -1 ? statement.length : end + 1;
    } else break;
  }
  return i;
}

const statements = splitStatements(readFileSync(SOURCE, "utf8"));
let removed = 0;
const output = statements.map((statement) => {
  const at = codeStart(statement);
  const code = statement.slice(at).toLowerCase();
  const table = CONTENT_TABLES.find((t) => code.startsWith(`insert into public.${t} `) || code.startsWith(`insert into public.${t}(`));
  if (!table) return statement;
  removed++;
  return `${statement.slice(0, at)}-- [fresh install] content insert into public.${table} removed here —\n-- the content is copied from the old project by scripts/copy-reference-data.mjs.`;
});

const header = `-- Qunity — full database structure for a NEW, EMPTY Supabase project.
--
-- GENERATED by scripts/build-fresh-install.mjs from supabase/schema.sql — do
-- not edit by hand; change schema.sql and regenerate. It replays schema.sql's
-- whole history with the content inserts taken out (${removed} of them).
--
-- Run once, in the new project's SQL Editor, on an empty database. Then copy
-- the content (stages, workouts, exercises, challenges, tips) with
-- scripts/copy-reference-data.mjs. Do NOT also run seed.sql.

`;

writeFileSync(TARGET, header + output.join(""));
console.log(`Wrote ${TARGET}: ${statements.length} statements, ${removed} content inserts removed.`);
